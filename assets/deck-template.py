# -*- coding: utf-8 -*-
"""建全案 PPT —— 骨架。每个原语各演示一次，照着往下加页即可。

复制到 <产出>/_src/deck.py 再改。跑法：
    cd <产出>/_src && python3 deck.py
然后一定要跑自检：
    python3 ~/.claude/skills/proposal-creator/scripts/render.py <产出>/全案-v1.pptx /tmp/r

原语都自己算高度、自己贴边，所以顺序往下排就行。但**排完必须跑 render.py**——
它能查出溢出和越界，肉眼看缩略图看不出来。
"""
import os, sys
SCRIPTS = os.path.expanduser('~/.claude/skills/proposal-creator/scripts')
sys.path.insert(0, SCRIPTS)
from kit import *

OUT = CFG['base'] + '全案-v1.pptx'
prs = deck()

# ══ 1 封面 ════════════════════════════════════════════
cover(prs, '主标题写在这', '副标题一句话', 'EN SUBTITLE', '2026.09')

# ══ 2 目录 ════════════════════════════════════════════
# (编号, 中文, 英文, 本章回答什么, 是否重心)。重心章节用章节色，其余压灰。
toc(prs, [
    ('01', SEC_NAME['01'][0], SEC_NAME['01'][1], '这一章回答客户的哪个问题', True),
    ('02', SEC_NAME['02'][0], SEC_NAME['02'][1], '这一章回答客户的哪个问题', False),
    ('03', SEC_NAME['03'][0], SEC_NAME['03'][1], '这一章回答客户的哪个问题', True),
])

# ══ 3 章节页 ══════════════════════════════════════════
divider(prs, '01')

# ══ 4 内容页 · 卡片行 ══════════════════════════════════
# page() 返回 (slide, y)。y 是标题+导语下面的第一条可用位置。
s, y = page(prs, '01', '这页的标题', '一句话导语，不超过两行。',
            foot_txt='数据来源：〔出处〕。')
y = cards_row(s, y + 0.10, 2.10, [
    ('第一张卡', '两行以内的正文。一页只讲一件事，这里放支撑。'),
    ('第二张卡', '正文写短。支撑放不下就拆页，不要挤。'),
    ('第三张卡', '这张是要强调的。'),
], highlight={2})                       # highlight 给下标集合，不是整块亮色
note_bar(s, '这页如果只能记一句，就是这句。', y + 0.30)

# ══ 5 内容页 · 数字 ═══════════════════════════════════
# 数字只做证据不做修辞，所以每个数字底下都要有出处。
s, y = page(prs, '02', '三个数字', '数字必须有出处，没出处的不要放上来。')
w = CW / 3
for i, (big, unit, label) in enumerate([
        ('00', '单位', '这个数字说明什么'),
        ('00', '单位', '这个数字说明什么'),
        ('00', '单位', '这个数字说明什么')]):
    stat(s, M + i * w, y + 0.50, w - 0.4, big, unit, label)
foot(s, '数据来源：〔出处〕。〔口径说明〕')

# ══ 6 内容页 · 表格 ═══════════════════════════════════
# 表格不超过 6–7 行，超了就拆页或只留结论行。
s, y = page(prs, '02', '一张表', '表格超过七行就该拆页。')
table(s, M, y + 0.10, CW,
      ['列一', '列二', '列三'],
      [['内容', '内容', '内容'],
       ['内容', '内容', '内容'],
       ['内容', '内容', '内容']],
      col_w=[1.4, 1, 1], hi={1})

# ══ 7 内容页 · 大字主张 ═══════════════════════════════
# 主张页是呼吸点，一页就这一句，别的都不要。
s, y = page(prs, '03', '', '')
quote(s, '大字主张写在这，\n可以断成两行。', y + 0.60, size=40,
      sub='底下补一句小字。')

# ══ 8 内容页 · 人物卡 ═════════════════════════════════
# slot 对应 产出/素材/<slot>.jpg。有真图用真图，没有就出姓名卡。
# 素材没到位时，姓名卡是设计过的，不是灰块——不要用灰块占位。
s, y = page(prs, '03', '人选方向', '一句话说清这一类人的共同点。')
gap, n = 0.30, 3
cw3 = (CW - (n - 1) * gap) / n
for i, (nm, role, why) in enumerate([
        ('姓名一', '身份', '为什么是他：履历、调性、风险，这三样才是要写的。'),
        ('姓名二', '身份', '为什么是他。'),
        ('姓名三', '身份', '为什么是他。')]):
    cx = M + i * (cw3 + gap)
    portrait(s, cx, y + 0.12, cw3, 2.30, nm, role, slot='P07-%d' % (i + 1))
    t = tb(s, cx, y + 2.54, cw3, 0.80)
    R(P(t, first=True, line=1.55), why, 10.5, False, onN_2)

# ══ 尾页 ══════════════════════════════════════════════
end(prs, '收尾就这一句，\n为这份方案单独想。')

page_number(prs)
prs.save(OUT)
print('✅ %s\n   %d 页 · %.0f KB' % (OUT, len(prs.slides._sldIdLst),
                                     os.path.getsize(OUT) / 1024))
print('   下一步：python3 %s/render.py %s /tmp/r' % (SCRIPTS, OUT))
